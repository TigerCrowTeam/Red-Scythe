"""Independent wire expectations, malformed layouts and template persistence."""

import copy
import zlib

import pytest

from packet_radio.configuration.forms import FormSession
from packet_radio.packets.template import PacketTemplate, load_template, save_template


def template():
    value = PacketTemplate.new(FormSession.new().report.config)
    value.payload = "abc"
    value.fields = [
        dict(name="type", kind="uint", width=1, order="big", value="42"),
        dict(name="length", kind="length", width=2, order="little", value=""),
        value.fields[0],
        dict(name="check", kind="crc32", width=4, order="little", value=""),
    ]
    return value


def test_wire_length_crc_and_inspection():
    t = template()
    prefix = b"\x2a\x0a\x00abc"
    expected = prefix + zlib.crc32(prefix).to_bytes(4, "little")
    assert t.encode()[0] == expected
    fields = t.inspect(expected)
    assert [f.value for f in fields[:3]] == ["42", "10", "abc"]
    with pytest.raises(ValueError, match="mismatch"):
        t.inspect(expected[:-1] + bytes([expected[-1] ^ 1]))
    assert "Length:" in t.preview(FormSession.new().report.config)


@pytest.mark.parametrize(
    "change",
    [
        lambda t: t.fields[0].update(value="256"),
        lambda t: t.fields[0].update(width=3),
        lambda t: t.fields[0].update(name="payload"),
        lambda t: t.fields[1].update(width=True),
        lambda t: t.fields[2].update(width=1),
        lambda t: t.fields[3].update(width=2),
        lambda t: t.fields.append(copy.deepcopy(t.fields[2])),
        lambda t: setattr(t, "payload", "a" * 1024),
        lambda t: setattr(t, "payload_encoding", "unknown"),
    ],
)
def test_invalid_layouts_rejected(change):
    t = template()
    change(t)
    with pytest.raises(ValueError):
        t.encode()


def test_save_roundtrip_conflict_and_limits(tmp_path):
    t = template()
    path = tmp_path / "packet.yaml"
    saved = save_template(t, path)
    assert load_template(path).document() == t.document()
    t.payload = "new"
    with pytest.raises(ValueError, match="exists"):
        save_template(t, path)
    saved = save_template(t, path, expected=saved)
    path.write_text("external")
    with pytest.raises(ValueError, match="changed"):
        save_template(t, path, expected=saved)
    path.write_bytes(b"x" * 65537)
    with pytest.raises(ValueError, match="64 KiB"):
        load_template(path)


def test_payload_text_hex_and_radio_mismatch():
    cfg = FormSession.new().report.config
    t = PacketTemplate.new(cfg)
    t.payload_encoding, t.payload = "hex", "00 ff 10"
    assert t.validate_radio(cfg)[0] == b"\x00\xff\x10"
    t.frame["sync"] = "deadbeef"
    with pytest.raises(ValueError, match="framing differs"):
        t.validate_radio(cfg)


def test_received_values_become_editable_and_crc_recalculates():
    t = template()
    source = template()
    source.fields[0]["value"] = "99"
    source.payload = "new contents"
    data = source.encode()[0]
    edited = t.with_packet(data)
    assert edited.fields[0]["value"] == "99"
    assert edited.payload_encoding == "hex"
    assert edited.encode()[0] == data
    edited.fields[0]["value"] = "100"
    assert edited.encode()[0] != data
    assert edited.inspect(edited.encode()[0])[0].value == "100"


def test_standard_crc16_vector_and_binary_text_inspection():
    t = template()
    t.fields = [
        dict(name="payload", kind="payload", width=0, order="big", value=""),
        dict(name="crc", kind="crc16", width=2, order="big", value=""),
    ]
    t.payload = "123456789"
    assert t.encode()[0] == b"123456789\x29\xb1"
    t.fields = [dict(name="text", kind="text", width=1, order="big", value="a"), t.fields[0]]
    copied = t.with_packet(b"\xff\x00")
    assert copied.fields[0]["kind"] == "hex"
    assert copied.encode()[0] == b"\xff\x00"


@pytest.mark.parametrize("mode", ["bpsk", "2fsk", "msk", "gmsk", "qpsk"])
def test_application_layout_all_generic_modulations(mode):
    session = FormSession.new()
    session.change("profile.packet.format", "generic-v5")
    session.change("profile.waveform.modulation", mode)
    t = template()
    t.packet_format, t.frame = "generic-v5", None
    assert t.validate_radio(session.report.config)[0] == t.encode()[0]
    assert "generated by the radio" in t.preview(session.report.config)


def test_fixed_radio_frame_size_and_integer_signedness():
    session = FormSession.new()
    session.draft.set("profile.packet.frame.length_bytes", 0)
    session.draft.set("profile.packet.frame.fixed_payload_bytes", 4)
    session.draft.set("profile.packet.max_payload_bytes", 4)
    config = session.draft.validate().config
    t = PacketTemplate.new(config)
    t.payload = "abc"
    with pytest.raises(ValueError, match="fixed size"):
        t.validate_radio(config)
    t.fields.insert(0, dict(name="signed", kind="int", width=1, order="little", value="-128"))
    assert t.validate_radio(config)[0] == b"\x80abc"
    assert t.inspect(t.encode()[0])[0].value == "-128"
